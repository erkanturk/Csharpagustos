namespace _15_MathMethods
{
    internal class Program
    {
        static void Main(string[] args)
        {
            /*Hazır method yapıları*/
            Console.WriteLine($"Pi:{Math.PI}");
            Console.WriteLine($"Karekök alma:{Math.Sqrt(100)}");
            Console.WriteLine($"Kuvvetini alma:{Math.Pow(2,3)}");
            Console.WriteLine($"Mutlak değer:{Math.Abs(-30)}");
            Console.WriteLine($"Max değer:{Math.Max(50,60)}");
            Console.WriteLine($"Min değer:{Math.Min(50,60)}");
            Console.WriteLine($"Tam Yuvarlama:{Math.Round(3.5)}");
            Console.WriteLine($"Yukarı Yuvarlama:{Math.Ceiling(3.001)}");
            Console.WriteLine($"Aşağı yuvarlama:{Math.Floor(3.99)}");



        }
    }
}
